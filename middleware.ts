import { NextResponse, type NextRequest } from "next/server";
import { createServerClient, type CookieOptions } from "@supabase/ssr";

export async function middleware(request: NextRequest) {
  let response = NextResponse.next({ request: { headers: request.headers } });

  const supabase = createServerClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
    {
      cookies: {
        get(name: string) {
          return request.cookies.get(name)?.value;
        },
        set(name: string, value: string, options: CookieOptions) {
          response.cookies.set({ name, value, ...options });
        },
        remove(name: string, options: CookieOptions) {
          response.cookies.set({ name, value: "", ...options });
        },
      },
    }
  );

  const { data: { session } } = await supabase.auth.getSession();

  const isPanelRoute = request.nextUrl.pathname.startsWith("/panel") &&
    !request.nextUrl.pathname.startsWith("/panel/login");
  const isDashboardRoute = request.nextUrl.pathname.startsWith("/dashboard");
  const isLeadDetailRoute = request.nextUrl.pathname.startsWith("/lead/");

  if ((isPanelRoute || isDashboardRoute || isLeadDetailRoute) && !session) {
    const redirectUrl = new URL("/panel/login", request.url);
    redirectUrl.searchParams.set("next", request.nextUrl.pathname);
    return NextResponse.redirect(redirectUrl);
  }

  return response;
}

export const config = {
  matcher: ["/panel/:path*", "/dashboard/:path*", "/lead/:path*"],
};
